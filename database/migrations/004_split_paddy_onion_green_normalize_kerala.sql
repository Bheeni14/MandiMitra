-- Migration 004 - Historical commodity identity and state-name corrections
--
--   a) Keralam -> Kerala            (dim_market.state, canonical state name is Kerala)
--   b) Rice    -> Paddy             (only the rows whose raw Agmarknet commodity was a Paddy spelling)
--   c) Onion   -> Onion Green       (only the rows whose raw Agmarknet commodity was "Onion Green")
--   d) map_commodity_crop           (Paddy -> Rice crop, idempotent, Rice commodity unchanged)
--
-- Evidence. The rows to move are listed explicitly in operational.migration_004_split_evidence,
-- generated by scripts/build_migration_004_mapping.py from the raw pages of
-- data/raw/agmarknet/2026-11-19 (off-project backup verified against its SHA-256 manifest,
-- aggregate 13b8fe7d7de3f984f652df5b3ee4aabe37d17348fafc84a244c3cf089d4fa4e3). Every evidence row
-- carries its raw file, position, raw commodity string and exact prices, and a fact row is moved
-- only when date, market, district, state, variety, grade and all three prices match exactly.
-- Actual Rice rows (raw commodity Rice / Rice(Fine/Superfine/Grade A)) are never touched.
--
-- Safety
--   * Only fact_price_daily.commodity_id and dim_market.state change. Prices, varieties, grades,
--     outlier flags, sources and ingestion timestamps are preserved exactly.
--   * The evidence must match all-or-nothing. On a database without these rows (demo, fresh) zero
--     rows match and only the new dimension rows are added. A partial match aborts.
--   * Totals (fact count, min/max/modal price sums, arrivals, markets) are asserted unchanged.
--   * Every check is a row in operational.migration_004_assertions whose CHECK constraint aborts
--     the whole migration transaction on the first failed check.
--   * Backup and audit tables are created without IF NOT EXISTS on purpose, so leftovers from an
--     earlier attempt abort instead of mixing.
--   * Rollback is database/rollbacks/004_split_paddy_onion_green_normalize_kerala.down.sql.
--   * This file intentionally contains no colon or semicolon inside comments or literals so it
--     runs unchanged on PostgreSQL and on the Demo SQLite warehouse.
-- =============================================================================

