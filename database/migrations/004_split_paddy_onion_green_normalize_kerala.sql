-- 3b. Commodity-to-crop mapping Paddy -> Rice (idempotent). Rice crop is ensured if missing.
--     Separate Paddy and Rice commodity rows are preserved. Only the mapping row is added.
CREATE TABLE operational.migration_004_crop_mapping_backup (
    commodity_name         TEXT NOT NULL,
    crop_name              TEXT NOT NULL,
    crop_existed_before    BOOLEAN NOT NULL,
    mapping_existed_before BOOLEAN NOT NULL,
    PRIMARY KEY (commodity_name, crop_name)
);

INSERT INTO operational.migration_004_crop_mapping_backup (
    commodity_name, crop_name, crop_existed_before, mapping_existed_before
)
SELECT
    'Paddy',
    'Rice',
    EXISTS (SELECT 1 FROM warehouse.dim_crop WHERE crop_name = 'Rice'),
    EXISTS (
        SELECT 1
        FROM warehouse.map_commodity_crop m
        JOIN warehouse.dim_commodity c ON c.commodity_id = m.commodity_id
        JOIN warehouse.dim_crop cr ON cr.crop_id = m.crop_id
        WHERE c.commodity_name = 'Paddy'
          AND cr.crop_name = 'Rice'
    );

INSERT INTO warehouse.dim_crop (crop_name, crop_type)
SELECT 'Rice', 'Cereal'
WHERE NOT EXISTS (SELECT 1 FROM warehouse.dim_crop WHERE crop_name = 'Rice');

INSERT INTO warehouse.map_commodity_crop (commodity_id, crop_id)
SELECT c.commodity_id, cr.crop_id
FROM warehouse.dim_commodity c
JOIN warehouse.dim_crop cr ON cr.crop_name = 'Rice'
WHERE c.commodity_name = 'Paddy'
  AND NOT EXISTS (
        SELECT 1
        FROM warehouse.map_commodity_crop m
        WHERE m.commodity_id = c.commodity_id
          AND m.crop_id = cr.crop_id
    );

